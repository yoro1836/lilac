std::string detect_hardware(const std::string& root_dir) {
    static const char* kPreferred[] = {"vine", "ranchu", "goldfish"};
    for (const char* hw : kPreferred) {
        if (path_exists(path_join(root_dir, std::string("init.") + hw + ".rc"))) return hw;
    }
    return "";
}

std::string build_cmdline(const BootParams& p) {
    std::string c;
    if (!p.hardware.empty()) c += "androidboot.hardware=" + p.hardware + " ";
    c += "androidboot.selinux=permissive androidboot.console=console androidboot.vine=1";
    c += " androidboot.vine.instance=" + p.instance_id;
    c += " androidboot.vine.width=" + std::to_string(p.display_width);
    c += " androidboot.vine.height=" + std::to_string(p.display_height);
    c += " androidboot.vine.dpi=" + std::to_string(p.display_dpi);
    c += " androidboot.vine.ram_mb=" + std::to_string(p.ram_mb);
    c += std::string(" androidboot.vine.root=") + (p.rooted ? "1" : "0");
    c += std::string(" androidboot.vine.qemu32=") + (p.qemu_32bit ? "1" : "0");
    if (!p.net_ip.empty()) {
        c += " androidboot.vine.net_ip=" + p.net_ip + " androidboot.vine.net_gw=" + p.net_gateway;
        c += " androidboot.vine.net_dns=" + p.net_dns;
    }
    c += "\n";
    return c;
}

std::string build_boot_prop(const BootParams& p) {
    std::string s = "# Generated by the Wayondroid runtime on every start, do not edit.\n";
    if (!p.hardware.empty()) s += "ro.boot.hardware=" + p.hardware + "\n";
    s += "ro.boot.vine=1\n";
    s += "ro.boot.vine.instance=" + p.instance_id + "\n";
    s += "ro.boot.vine.width=" + std::to_string(p.display_width) + "\n";
    s += "ro.boot.vine.height=" + std::to_string(p.display_height) + "\n";
    s += "ro.boot.vine.dpi=" + std::to_string(p.display_dpi) + "\n";
    s += "ro.boot.vine.ram_mb=" + std::to_string(p.ram_mb) + "\n";
    s += std::string("ro.boot.vine.root=") + (p.rooted ? "1" : "0") + "\n";
    s += std::string("ro.boot.vine.qemu32=") + (p.qemu_32bit ? "1" : "0") + "\n";
    if (!p.net_ip.empty()) {
        s += "ro.boot.vine.net_ip=" + p.net_ip + "\n";
        s += "ro.boot.vine.net_gw=" + p.net_gateway + "\n";
        s += "ro.boot.vine.net_dns=" + p.net_dns + "\n";
    }
    s += "ro.sf.lcd_density=" + std::to_string(p.display_dpi) + "\n";
    return s;
}

bool write_managed_block(const std::string& path, const std::vector<std::string>& lines) {
    static const std::string kBegin = "# vine-begin";
    static const std::string kEnd = "# vine-end";

    std::string existing = read_file(path).value_or("");
    std::string kept;
    bool skipping = false;
    for (const auto& line : split_lines(existing)) {
        if (line == kBegin) { skipping = true; continue; }
        if (line == kEnd) { skipping = false; continue; }
        if (!skipping) kept += line + "\n";
    }
    if (!kept.empty() && kept.back() != '\n') kept += "\n";

    std::string block = kBegin + "\n";
    for (const auto& l : lines) block += l + "\n";
    block += kEnd + "\n";
    return write_file_atomic(path, kept + block, 0600);
}

bool file_contains(const std::string& path, const std::string& needle, size_t max_bytes) {
    auto data = read_file_prefix(path, max_bytes);
    if (!data || needle.empty()) return false;
    return std::search(data->begin(), data->end(), needle.begin(), needle.end()) != data->end();
}

